async function pingCore(ctx, a, flavor = 'ping') {
  let count = Infinity; let target = null; let iface = null; let interval = 1000;
  for (let i = 0; i < a.length; i++) {
    if (a[i] === '-c') count = Number(a[++i]) || 1;
    else if (/^-c\d+$/.test(a[i])) count = Number(a[i].slice(2));
    else if (a[i] === '-I') iface = a[++i];
    else if (a[i] === '-i') interval = Math.max(200, Number(a[++i]) * 1000);
    else if (a[i] === '-4' || a[i] === '-n' || a[i] === '-q') continue;
    else if (a[i] === '-W' || a[i] === '-s' || a[i] === '-t') i++;
    else if (!a[i].startsWith('-')) target = a[i];
  }
  if (!target) { ctx.err('ping: usage error: Destination address required'); return 1; }
  const vm = ctx.vm;
  let ip = target;
  if (!isIp(target)) {
    const r = resolve(state, vm.id, target, { servers: resolverServers(ctx) });
    if (r.error) {
      await ctx.sleep(r.error === 'timeout' ? 1800 : 300);
      ctx.err(r.error === 'nxdomain' ? `ping: ${target}: Name or service not known` : `ping: ${target}: Temporary failure in name resolution`);
      ctx.didactic({ title: `Resolución DNS de ${target}`, explain: [r.error === 'nxdomain' ? `El servidor DNS ${r.server} responde que el nombre no existe (NXDOMAIN).` : r.error === 'noservers' ? 'La máquina no tiene ningún servidor DNS configurado.' : `No se ha podido contactar con el servidor DNS ${r.server || ''}. ¿Hay ruta hacia él? ¿Tiene la VM salida a Internet?`], status: 'dns' });
      ctx.event({ type: 'dns', name: target, ok: false });
      return 2;
    }
    ip = r.ip;
  }
  let srcIp = null;
  if (iface) {
    const i = ifaceOf(ctx, iface) || ctx.rt.ifaces.find((x) => x.addrs.some((ad) => ad.ip === iface));
    if (!i) { ctx.err(`ping: SO_BINDTODEVICE ${iface}: No such device`); return 2; }
    srcIp = i.addrs[0]?.ip;
  }
  const first = send(state, vm.id, ip, { srcIp });
  learnArp(ctx, first);
  const label = isIp(target) ? ip : `${target} (${ip})`;
  if (first.status === 'noroute') {
    ctx.err(`ping: connect: Network is unreachable`);
    explainNet(ctx, `ping ${target}`, first);
    ctx.event({ type: 'ping', dst: ip, ok: false, status: 'noroute' });
    return 2;
  }
  const from = PTR[ip] && first.status === 'ok' ? `${PTR[ip]} (${ip})` : ip;
  ctx.line(`PING ${isIp(target) ? ip : target} (${ip}) 56(84) bytes of data.`);
  const t0 = Date.now();
  let sent = 0; let recv = 0; let errs = 0; const times = [];
  let last = first;
  while (sent < count && sent < 2000) {
    const r = sent === 0 ? first : send(state, vm.id, ip, { srcIp });
    last = r;
    sent++;
    if (r.status === 'ok' && !(r.conflict && Math.random() < 0.45)) {
      const ms = jitter(Math.max(0.05, r.rtt), Math.random());
      times.push(ms); recv++;
      ctx.line(`64 bytes from ${from}: icmp_seq=${sent} ttl=${r.ttl} time=${fmtMs(ms)} ms${r.conflict && Math.random() < 0.3 ? ' (DUP!)' : ''}`);
      i_count(ctx, r);
    } else if (r.status === 'host_unreach' || r.status === 'net_unreach' || r.status === 'admin') {
      errs++;
      if (sent >= 3 || count <= 3 || r.errFrom !== r.srcIp) ctx.line(`From ${r.errFrom || r.srcIp} icmp_seq=${sent} ${r.status === 'net_unreach' ? 'Destination Net Unreachable' : r.status === 'admin' ? 'Packet filtered' : 'Destination Host Unreachable'}`);
    }
    if (sent >= count) break;
    if (!(await ctx.sleep(interval))) break;
  }
  const loss = sent ? Math.round(((sent - recv) / sent) * 100) : 0;
  const time = Date.now() - t0 + (sent > 1 ? 3 : 0);
  ctx.line(`\n--- ${isIp(target) ? ip : target} ping statistics ---`);
  ctx.line(`${sent} packets transmitted, ${recv} received,${errs ? ` +${errs} errors,` : ''} ${loss}% packet loss, time ${time}ms`);
  if (times.length) {
    const min = Math.min(...times); const max = Math.max(...times); const avg = times.reduce((x, y) => x + y, 0) / times.length;
    const mdev = Math.sqrt(times.reduce((x, y) => x + (y - avg) ** 2, 0) / times.length);
    ctx.line(`rtt min/avg/max/mdev = ${min.toFixed(3)}/${avg.toFixed(3)}/${max.toFixed(3)}/${mdev.toFixed(3)} ms`);
  } else if (errs) ctx.line(`pipe ${Math.min(errs, 4)}`);
  explainNet(ctx, `ping ${target}`, last);
  ctx.event({ type: 'ping', dst: ip, name: target, ok: recv > 0, status: last.status, target: last.target?.id, recv, conflict: !!(first.conflict || last.conflict) });
  return recv > 0 ? 0 : 1;
}
