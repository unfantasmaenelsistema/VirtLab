def('ls dir', (ctx, a) => {
  const flags = a.filter((x) => x.startsWith('-')).join('');
  const targets = a.filter((x) => !x.startsWith('-'));
  const long = flags.includes('l');
  const all = flags.includes('a');
  const files = fileMap(ctx);
  const dirs = dirSet(ctx);
  let code = 0;
  for (const t of targets.length ? targets : ['.']) {
    const p = absPath(ctx, t);
    if (files[p] !== undefined && !dirs.has(p)) { ctx.line(long ? `-rw-r--r-- 1 root root ${String(files[p].length).padStart(5)} ${lsDate()} ${t}` : t); continue; }
    if (!dirs.has(p)) { ctx.err(`ls: cannot access '${t}': No such file or directory`); code = 2; continue; }
    if (!canRead(ctx, p)) { ctx.err(`ls: cannot open directory '${t}': Permission denied`); code = 2; continue; }
    const pre = p === '/' ? '/' : `${p}/`;
    const names = new Set();
    for (const d of dirs) if (d !== p && d.startsWith(pre) && !d.slice(pre.length).includes('/')) names.add(d.slice(pre.length) + '/');
    for (const f of Object.keys(files)) if (f.startsWith(pre) && !f.slice(pre.length).includes('/') && !names.has(f.slice(pre.length) + '/')) names.add(f.slice(pre.length));
    if (p === homeOf(ctx.sess.user) && all) ['.bashrc', '.profile', '.bash_logout'].forEach((x) => names.add(x));
    let list = [...names].filter((n) => all || !n.startsWith('.')).sort((x, y) => x.localeCompare(y));
    if (targets.length > 1) ctx.line(`${t}:`);
    if (long) {
      ctx.line(`total ${list.length * 4}`);
      if (all) list = ['./', '../', ...list];
      for (const n of list) {
        const isD = n.endsWith('/');
        const name = n.replace(/\/$/, '');
        const owner = p.startsWith('/home/') ? ctx.sess.user : 'root';
        ctx.line(`${isD ? 'drwxr-xr-x' : '-rw-r--r--'} ${isD ? 2 : 1} ${owner.padEnd(7)} ${owner.padEnd(7)} ${String(isD ? 4096 : (files[pre + name]?.length || 0)).padStart(5)} ${lsDate()} ${name}`);
      }
    } else if (list.length) ctx.line(list.map((n) => n.replace(/\/$/, '')).join('  '));
  }
  return code;
});
