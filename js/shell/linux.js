export async function sshClient(ctx, a) {
  let port = 22; let user = ctx.sess.user; let host = null;
  for (let i = 0; i < a.length; i++) {
    if (a[i] === '-p') port = Number(a[++i]);
    else if (a[i] === '-l') user = a[++i];
    else if (!a[i].startsWith('-')) { if (!host) host = a[i]; }
  }
  if (!host) { ctx.err('usage: ssh [-46AaCfGgKkMNnqsTtVvXxYy] [-B bind_interface] [-b bind_address]\n           [-c cipher_spec] [-D [bind_address:]port] [-E log_file]\n           [-l login_name] [-p port] destination [command [argument ...]]'); return 255; }
  if (host.includes('@')) [user, host] = host.split('@');
  const fromId = ctx.sess.kind === 'host' ? HOST_ID : ctx.vm.id;
  const rr = resolve(state, fromId, host, ctx.sess.kind === 'vm' ? { servers: resolverServers(ctx) } : {});
  if (rr.error) { ctx.err(`ssh: Could not resolve hostname ${host}: ${ctx.sess.kind === 'host' ? 'Host desconocido.' : 'Temporary failure in name resolution'}`); return 255; }
  const res = send(state, fromId, rr.ip, { proto: 'tcp', port });
  if (res.status === 'timeout') { if (!(await ctx.sleep(2500))) return 130; }
  if (res.status !== 'ok') {
    const why = res.status === 'refused' ? 'Connection refused' : res.status === 'noroute' ? 'Network is unreachable' : res.status === 'host_unreach' ? 'No route to host' : 'Connection timed out';
    ctx.err(`ssh: connect to host ${host} port ${port}: ${why}`);
    explainNet(ctx, `ssh ${user}@${host}`, res);
    ctx.event({ type: 'ssh', dst: rr.ip, port, ok: false, error: res.status });
    return 255;
  }
  const owner = serviceOwner(res);
  if (owner?.kind !== 'vm') { await ctx.sleep(400); ctx.err(`${user}@${host}: Permission denied (publickey,password).`); return 255; }
  const tvm = owner.vm;
  const tc = vmContent(state, tvm);
  const fp = hostKeyFp(tvm);
  const kh = ctx.sess.kind === 'host' ? (state.host.knownHosts ||= {}) : ((ctx.content.knownHosts ||= {}));
  const key = port === 22 ? rr.ip : `[${rr.ip}]:${port}`;
  if (kh[key] && kh[key] !== fp) {
    ctx.err(`@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@\n@    WARNING: REMOTE HOST IDENTIFICATION HAS CHANGED!     @\n@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@\nIT IS POSSIBLE THAT SOMEONE IS DOING SOMETHING NASTY!\nSomeone could be eavesdropping on you right now (man-in-the-middle attack)!\nIt is also possible that a host key has just been changed.\nThe fingerprint for the ED25519 key sent by the remote host is\n${fp}.\nPlease contact your system administrator.\nAdd correct host key in ${ctx.sess.kind === 'host' ? 'C:\\\\Users\\\\alumno/.ssh/known_hosts' : `${homeOf(ctx.sess.user)}/.ssh/known_hosts`} to get rid of this message.\nOffending ED25519 key in known_hosts:1\nHost key for ${key} has changed and you have requested strict checking.\nHost key verification failed.`);
    ctx.didactic({ title: 'La clave del servidor SSH ha cambiado', status: 'error', explain: ['Ya te habías conectado a esa IP y el servidor presentaba otra clave. Pasa, por ejemplo, cuando otra VM obtiene la misma IP. Si es legítimo, borra la entrada con: ssh-keygen -R ' + key] });
    return 255;
  }
  if (!kh[key]) {
    ctx.line(`The authenticity of host '${key} (${rr.ip})' can't be established.\nED25519 key fingerprint is ${fp}.\nThis key is not known by any other names.`);
    const ans = await ctx.read('Are you sure you want to continue connecting (yes/no/[fingerprint])? ');
    if (ans === null) return 130;
    if (!/^yes$/i.test(ans.trim())) { ctx.err('Host key verification failed.'); return 255; }
    kh[key] = fp;
    ctx.line(`Warning: Permanently added '${key}' (ED25519) to the list of known hosts.`);
  }
  const u = tc.users.find((x) => x.name === user);
  for (let i = 0; i < 3; i++) {
    const p = await ctx.read(`${user}@${rr.ip}'s password: `, { hidden: true });
    if (p === null) return 130;
    if (u && !u.root && u.pass === p) {
      ctx.line(motd(tc));
      ctx.line(`Last login: ${new Date(Date.now() - 3600 * 1000).toUTCString()} from ${res.forwardedTo ? '10.0.2.2' : res.srcIp || '10.0.2.2'}`);
      ctx.event({ type: 'ssh', dst: rr.ip, port, ok: true, vm: tvm.id, user, forwarded: !!res.forwardedTo });
      explainNet(ctx, `ssh ${user}@${host}`, res, ['Sesión SSH abierta.']);
      ctx.sess.pushSession?.({ kind: 'vm', vmId: tvm.id, user, cwd: homeOf(user), remote: true, from: rr.ip });
      return 0;
    }
    await ctx.sleep(600);
    ctx.err('Permission denied, please try again.');
  }
  ctx.err(`${user}@${rr.ip}: Permission denied (publickey,password).`);
  return 255;
}
