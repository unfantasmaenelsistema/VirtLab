function resolvConf(ctx) {
  const c = ctx.content;
  if (c.files['/etc/resolv.conf.user'] !== undefined) return c.files['/etc/resolv.conf.user'];
  if (c.os === 'ubuntu') return '# This is /run/systemd/resolve/stub-resolv.conf managed by man:systemd-resolved(8).\n# Do not edit.\n#\n# This file might be symlinked as /etc/resolv.conf. If you\'re looking at\n# /etc/resolv.conf and seeing this text, you have followed the symlink.\n#\n# This is a dynamic resolv.conf file for connecting local clients to the\n# internal DNS stub resolver of systemd-resolved. This file lists all\n# configured search domains.\n#\n# Run "resolvectl status" to see details about the uplink DNS servers\n# currently in use.\n#\n# Third party programs should typically not access this file directly, but only\n# through the symlink at /etc/resolv.conf. To manage man:resolv.conf(5) in a\n# different way, replace this symlink by a static file or a different symlink.\n#\n# See man:systemd-resolved.service(8) for details about the supported modes of\n# operation for /etc/resolv.conf.\n\nnameserver 127.0.0.53\noptions edns0 trust-ad\nsearch .\n';
  const dns = dnsServersOf(ctx.vm);
  if (dns.length) return `# Generated by NetworkManager\nsearch home\n${dns.map((d) => `nameserver ${d}`).join('\n')}\n`;
  return c.files['/etc/resolv.conf'] || '';
}

function resolverServers(ctx) {
  const c = ctx.content;
  const txt = resolvConf(ctx);
  const ns = [...txt.matchAll(/^\s*nameserver\s+(\S+)/gm)].map((m) => m[1]).filter(isIp);
  if (c.os === 'ubuntu' && ns.includes('127.0.0.53') && c.files['/etc/resolv.conf.user'] === undefined) return dnsServersOf(ctx.vm);
  return ns.filter((x) => x !== '127.0.0.53');
}

