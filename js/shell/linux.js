export function completeLinux(sess, before) {
  const words = before.split(/\s+/);
  const vm = getVm(sess.vmId);
  const c = vmContent(state, vm);
  if (!c) return [];
  if (words.length <= 1) return Object.keys(CMDS).filter((x) => !x.startsWith('_') && x.startsWith(words[0]) && (!PKG_OF[x] || hasPkg(c, PKG_OF[x]))).sort();
  const w = words[words.length - 1];
  const ifn = (vm.rt?.ifaces || []).map((i) => i.name);
  if (ifn.some((n) => n.startsWith(w)) && !w.includes('/')) return ifn.filter((n) => n.startsWith(w));
  const ctx = { sess, content: c, vm, rt: vm.rt };
  const base = w.includes('/') ? w.slice(0, w.lastIndexOf('/') + 1) : '';
  const dir = absPath(ctx, base || '.');
  const pre = dir === '/' ? '/' : `${dir}/`;
  const names = new Set();
  for (const d of dirSet(ctx)) if (d.startsWith(pre) && d !== dir && !d.slice(pre.length).includes('/')) names.add(d.slice(pre.length) + '/');
  for (const f of Object.keys(fileMap(ctx))) if (f.startsWith(pre) && !f.slice(pre.length).includes('/')) names.add(f.slice(pre.length));
  const part = w.slice(base.length);
  return [...names].filter((n) => n.startsWith(part)).map((n) => base + n).sort();
}
