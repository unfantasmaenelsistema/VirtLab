function sharedMounts(ctx) {
  const vm = ctx.vm; const c = ctx.content;
  if (!c.ga || !vm.rt?.gaActive) return [];
  return vm.shared.filter((s) => s.automount).map((s) => ({ ...s, mp: s.mountPoint || `/media/sf_${s.name}` }));
}

function absPath(ctx, p) {
  if (!p) return ctx.sess.cwd;
  if (p === '~' || p.startsWith('~/')) p = homeOf(ctx.sess.user) + p.slice(1);
  if (!p.startsWith('/')) p = `${ctx.sess.cwd.replace(/\/$/, '')}/${p}`;
  const parts = [];
  for (const s of p.split('/')) { if (!s || s === '.') continue; if (s === '..') parts.pop(); else parts.push(s); }
  return '/' + parts.join('/');
}

function fileMap(ctx) {
  const c = ctx.content;
  const f = { ...c.files };
  delete f['/etc/resolv.conf.user'];
  f['/etc/resolv.conf'] = resolvConf(ctx);
  f['/etc/os-release'] = osRelease(c);
  f['/etc/issue'] = `${OS_TYPES[c.os].pretty} \\n \\l\n\n`;
  f['/proc/sys/net/ipv4/ip_forward'] = `${ctx.rt?.ipForward ?? 0}\n`;
  f['/etc/shadow'] = '';
  f['/etc/passwd'] = `root:x:0:0:root:/root:/bin/bash\ndaemon:x:1:1:daemon:/usr/sbin:/usr/sbin/nologin\n${c.users.filter((u) => !u.root).map((u, i) => `${u.name}:x:${1000 + i}:${1000 + i}:${u.name},,,:/home/${u.name}:/bin/${c.os === 'kali' ? 'zsh' : 'bash'}`).join('\n')}\n`;
  if (c.pkgs.includes('apache2') || c.pkgs.includes('nginx')) { if (f['/var/www/html/index.html'] === undefined) f['/var/www/html/index.html'] = '(página por defecto de Apache2/nginx)\n'; }
  f['/var/log/syslog'] = (ctx.vm.log || []).slice(-12).map((l) => `${nowStamp().replace(' ', 'T')} ${c.hostname} kernel: ${l.slice(16)}`).join('\n') + '\n';
  for (const m of sharedMounts(ctx)) for (const file of (state.hostFiles.shared?.[m.hostPath] || [])) f[`${m.mp}/${file.name}`] = file.text || '';
  if (ctx.rt?.cdMounted) { f['/mnt/VBoxLinuxAdditions.run'] = '#!/bin/sh\n# VirtualBox Guest Additions installer\n'; f['/mnt/VBoxWindowsAdditions.exe'] = 'MZ'; f['/mnt/autorun.sh'] = '#!/bin/sh\n'; }
  return f;
}

function dirSet(ctx) {
  const set = new Set(BASE_DIRS);
  const c = ctx.content;
  for (const u of c.users) set.add(homeOf(u.name));
  for (const p of Object.keys(fileMap(ctx))) { let d = p.slice(0, p.lastIndexOf('/')) || '/'; while (d && !set.has(d)) { set.add(d); d = d.slice(0, d.lastIndexOf('/')) || '/'; } }
  for (const d of c.dirs || []) set.add(d);
  for (const m of sharedMounts(ctx)) set.add(m.mp);
  return set;
}

function canRead(ctx, p) {
  const root = isRoot(ctx);
  if (root) return true;
  if (p === '/etc/shadow') return false;
  for (const m of sharedMounts(ctx)) if (p.startsWith(m.mp) && !inGroup(ctx, 'vboxsf')) return false;
  if (p.startsWith('/root')) return false;
  const h = homeOf(ctx.sess.user);
  if (p.startsWith('/home/') && !p.startsWith(h)) return false;
  return true;
}
function canWrite(ctx, p) {
  if (isRoot(ctx)) return !p.startsWith('/proc') || p === '/proc/sys/net/ipv4/ip_forward';
  if (p.startsWith('/tmp/')) return true;
  for (const m of sharedMounts(ctx)) if (p.startsWith(m.mp + '/')) return inGroup(ctx, 'vboxsf') && !m.readonly;
  return p.startsWith(homeOf(ctx.sess.user) + '/');
}
const inGroup = (ctx, g) => (ctx.content.groups?.[g] || []).includes(ctx.sess.user) && !ctx.sess.staleGroups;
const isRoot = (ctx) => ctx.sess.user === 'root' || ctx.root;

function writeFile(ctx, p, text, append = false) {
  const c = ctx.content;
  const dir = p.slice(0, p.lastIndexOf('/')) || '/';
  if (!dirSet(ctx).has(dir)) return { error: 'No such file or directory' };
  if (!canWrite(ctx, p)) return { error: 'Permission denied' };
  if (p === '/proc/sys/net/ipv4/ip_forward') { ctx.rt.ipForward = String(text).trim().startsWith('1') ? 1 : 0; ctx.commit(); return {}; }
  if (p === '/etc/resolv.conf') { c.files['/etc/resolv.conf.user'] = append ? resolvConf(ctx) + text : text; ctx.commit(); return {}; }
  for (const m of sharedMounts(ctx)) if (p.startsWith(m.mp + '/')) {
    const list = (state.hostFiles.shared[m.hostPath] ||= []);
    const name = p.slice(m.mp.length + 1);
    const ex = list.find((x) => x.name === name);
    if (ex) ex.text = append ? (ex.text || '') + text : text; else list.push({ name, text, size: text.length });
    ctx.commit(); return {};
  }
  c.files[p] = append ? (c.files[p] ?? '') + text : text;
  ctx.commit();
  return {};
}

