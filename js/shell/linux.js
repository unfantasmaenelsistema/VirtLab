const PKG_OF = { ifconfig: 'net-tools', netstat: 'net-tools', route: 'net-tools', arp: 'net-tools', traceroute: 'traceroute', tracepath: 'iputils-tracepath', dig: 'dnsutils', nslookup: 'dnsutils', host: 'dnsutils', nmap: 'nmap', curl: 'curl', wget: 'wget', ssh: 'openssh-client', nc: 'netcat-traditional', netcat: 'netcat-traditional', tcpdump: 'tcpdump', ufw: 'ufw', netplan: 'netplan.io', ifup: 'ifupdown', ifdown: 'ifupdown', nmcli: 'network-manager', dhclient: 'isc-dhcp-client', sudo: 'sudo', htop: 'htop', sl: 'sl', dhcpd: 'isc-dhcp-server', resolvectl: 'systemd-resolved' };
function hasPkg(c, pkg) {
  if (pkg === 'dnsutils') return c.pkgs.includes('dnsutils') || c.pkgs.includes('bind9-dnsutils');
  if (pkg === 'iputils-tracepath') return c.pkgs.includes('iputils-tracepath') || c.os === 'kali';
  return c.pkgs.includes(pkg);
}
function notFound(ctx, cmd) {
  const c = ctx.content;
  const pkg = PKG_OF[cmd];
  if ((c.os === 'ubuntu' || c.os === 'kali') && pkg) {
    const real = pkg === 'dnsutils' && c.os === 'ubuntu' ? 'bind9-dnsutils' : pkg;
    if (c.os === 'kali') ctx.err(`Command '${cmd}' not found, but can be installed with:\nsudo apt install ${real}`);
    else ctx.err(`Command '${cmd}' not found, but can be installed with:\n\nsudo apt install ${real}\n`);
  } else ctx.err(`-bash: ${cmd}: command not found`);
  return 127;
}

