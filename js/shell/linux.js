export async function runLinux(term, sess, line) {
  const expanded = line.replace(/\$\(uname -r\)/g, OS_TYPES[vmContent(state, getVm(sess.vmId))?.os]?.kernel || '6.8.0').replace(/\$HOME/g, homeOf(sess.user)).replace(/\$USER/g, sess.user);
  let seq;
  try { seq = parse(expanded); } catch (e) { term.println(`-bash: ${e.message}`, 'term-err'); return 2; }
  let last = 0;
  for (const item of seq) {
    if (item.op === '&&' && last !== 0) continue;
    if (item.op === '||' && last === 0) continue;
    last = await runPipeline(term, sess, item.pipeline);
    if (term.aborted) { last = 130; break; }
  }
  sess.lastCode = last;
  return last;
}

async function runPipeline(term, sess, pipeline) {
  let input = null;
  let code = 0;
  for (let i = 0; i < pipeline.length; i++) {
    const c = pipeline[i];
    const isLast = i === pipeline.length - 1;
    const capture = !isLast || !!c.redir;
    const ctx = makeCtx(term, sess, capture);
    if (c.redir) {
      const p = absPath(ctx, c.redir.file);
      if (!canWrite(ctx, p) && !(c.redir.file === '/dev/null')) { ctx.err(`-bash: ${c.redir.file}: Permission denied`); return 1; }
    }
    code = await runCmd(ctx, c.argv, input);
    if (capture) {
      const lines = ctx.flushCapture();
      if (c.redir) {
        if (c.redir.file !== '/dev/null') {
          const r = writeFile(ctx, absPath(ctx, c.redir.file), lines.length ? lines.join('\n') + '\n' : '', c.redir.append);
          if (r.error) { ctx.err(`-bash: ${c.redir.file}: ${r.error}`); code = 1; }
        }
        input = [];
      } else input = lines;
    }
  }
  return code;
}

async function sudoAuth(ctx) {
  const c = ctx.content;
  const u = c.users.find((x) => x.name === ctx.sess.user);
  if (!u?.admin) { ctx.err(`${ctx.sess.user} is not in the sudoers file.  This incident will be reported.`); return false; }
  if (ctx.sess.sudoAt && Date.now() - ctx.sess.sudoAt < 15 * 60 * 1000) return true;
  for (let i = 0; i < 3; i++) {
    const p = await ctx.read(`[sudo] password for ${ctx.sess.user}: `, { hidden: true });
    if (p === null) return false;
    if (p === u.pass) { ctx.sess.sudoAt = Date.now(); return true; }
    ctx.err('Sorry, try again.');
  }
  ctx.err('sudo: 3 incorrect password attempts');
  return false;
}

async function polkit(ctx, action, what) {
  if (isRoot(ctx)) return true;
  const c = ctx.content;
  const u = c.users.find((x) => x.name === ctx.sess.user);
  ctx.line(`==== AUTHENTICATING FOR ${action} ====`);
  ctx.line(what);
  ctx.line(`Authenticating as: ${u.name}`);
  const p = await ctx.read('Password: ', { hidden: true });
  if (p !== u.pass) { ctx.line('polkit-agent-helper-1: pam_authenticate failed: Authentication failure'); ctx.line('==== AUTHENTICATION FAILED ===='); return false; }
  ctx.line('==== AUTHENTICATION COMPLETE ====');
  return true;
}

async function runCmd(ctx, argv, stdin) {
  if (!argv.length) return 0;
  let [cmd, ...args] = argv;
  // asignación de variables simple
  if (/^\w+=/.test(cmd) && !args.length) return 0;
  const c = ctx.content;
  if (cmd === 'sudo') {
    if (!hasPkg(c, 'sudo')) return notFound(ctx, 'sudo');
    if (!args.length) { ctx.line('usage: sudo -h | -K | -k | -V\nusage: sudo [-u user] command'); return 1; }
    if (!isRoot(ctx) && !(await sudoAuth(ctx))) return 1;
    if (args[0] === '-i' || args[0] === '-s' || (args[0] === 'su' && args.length <= 2)) { ctx.sess.userStack = [...(ctx.sess.userStack || []), { user: ctx.sess.user, cwd: ctx.sess.cwd }]; ctx.sess.user = 'root'; ctx.sess.cwd = '/root'; return 0; }
    ctx.root = true;
    [cmd, ...args] = args;
  }
  if (cmd.includes('/') && !cmd.startsWith('./') && !cmd.startsWith('/')) cmd = cmd.split('/').pop();
  const short = cmd.split('/').pop();
  const fn = CMDS[short] || (cmd.startsWith('/') || cmd.startsWith('./') ? CMDS.__exec : null);
  if (PKG_OF[short] && !hasPkg(c, PKG_OF[short])) return notFound(ctx, short);
  if (!fn) return notFound(ctx, short);
  ctx.cmdName = short;
  ctx.fullCmd = cmd;
  try {
    const r = await fn(ctx, args, stdin, cmd);
    return typeof r === 'number' ? r : 0;
  } catch (e) {
    console.error(e);
    ctx.err(`${short}: ${e.message}`);
    return 1;
  }
}

