function ifaceOf(ctx, name) { return ctx.rt.ifaces.find((i) => i.name === name); }
function linkUpOf(ctx, i) { return linkOf(state, ctx.vm, ctx.vm.nics[i.slot]).up; }

function ipAddrBlock(ctx, i, idx, { brief = false, v4only = false } = {}) {
  const nic = ctx.vm.nics[i.slot];
  const carrier = linkUpOf(ctx, i);
  const up = i.admin === 'up';
  const flags = up ? (carrier ? '<BROADCAST,MULTICAST,UP,LOWER_UP>' : '<NO-CARRIER,BROADCAST,MULTICAST,UP>') : '<BROADCAST,MULTICAST>';
  const st = up ? (carrier ? 'UP' : 'DOWN') : 'DOWN';
  if (brief) {
    const addrs = i.addrs.map((a) => `${a.ip}/${a.prefix}`).concat(up && carrier && !v4only ? [`${linkLocal6(nic.mac)}/64`] : []);
    return [`${i.name.padEnd(17)}${st.padEnd(15)}${addrs.join(' ')}`];
  }
  const out = [`${idx}: ${i.name}: ${flags} mtu 1500 qdisc ${up ? 'fq_codel' : 'noop'} state ${st} group default qlen 1000`, `    link/ether ${macColon(nic.mac)} brd ff:ff:ff:ff:ff:ff`];
  if (v4only) out.pop();
  for (const a of i.addrs) {
    const brd = a.prefix < 31 ? ` brd ${broadcastAddr(a.ip, a.prefix)}` : '';
    out.push(`    inet ${a.ip}/${a.prefix}${a.dyn ? ` metric ${100 + i.slot}` : ''}${brd} scope global ${a.dyn ? 'dynamic ' : ''}${i.name}`);
    if (a.dyn && i.lease) { const left = Math.max(0, Math.round(i.lease.time - (Date.now() - i.lease.at) / 1000)); out.push(`       valid_lft ${left}sec preferred_lft ${left}sec`); }
    else out.push('       valid_lft forever preferred_lft forever');
  }
  if (up && carrier && !v4only) out.push(`    inet6 ${linkLocal6(nic.mac)}/64 scope link`, '       valid_lft forever preferred_lft forever');
  return out;
}

function routeLines(ctx) {
  const out = [];
  const rt = ctx.rt;
  for (const r of rt.routes.filter((x) => x.dst === '0.0.0.0' && x.prefix === 0)) {
    const i = ifaceOf(ctx, r.dev);
    const src = i?.addrs.find((a) => sameNet(r.via, a.ip, a.prefix));
    const dead = !i || !linkUpOf(ctx, i) || i.admin !== 'up';
    out.push(`default via ${r.via} dev ${r.dev}${r.proto === 'dhcp' ? ` proto dhcp src ${src?.ip || ''}` : r.proto === 'static' ? ' proto static' : ''}${r.metric ? ` metric ${r.metric}` : ''}${dead ? ' linkdown' : ''}`);
  }
  for (const i of rt.ifaces) {
    if (i.admin !== 'up') continue;
    for (const a of i.addrs) {
      if (a.prefix >= 32) continue;
      const dead = !linkUpOf(ctx, i);
      out.push(`${networkAddr(a.ip, a.prefix)}/${a.prefix} dev ${i.name} proto kernel scope link src ${a.ip}${a.dyn ? ` metric ${100 + i.slot}` : ''}${dead ? ' linkdown' : ''}`);
      if (a.dyn && i.lease?.gw) out.push(`${i.lease.gw} dev ${i.name} proto dhcp scope link src ${a.ip} metric ${100 + i.slot}`);
    }
  }
  for (const r of rt.routes.filter((x) => !(x.dst === '0.0.0.0' && x.prefix === 0))) out.push(`${r.dst}/${r.prefix} via ${r.via} dev ${r.dev}${r.proto === 'static' ? ' proto static' : ''}`);
  return out;
}

