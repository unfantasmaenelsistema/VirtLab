async function traceCore(ctx, a, kind) {
  const target = a.filter((x) => !x.startsWith('-')).pop();
  if (!target) { ctx.err(`Usage:\n  ${kind} [ -46dFITnreAUDV ] [ -f first_ttl ] host [ packetlen ]`); return 2; }
  let ip = target;
  if (!isIp(target)) {
    const r = resolve(state, ctx.vm.id, target, { servers: resolverServers(ctx) });
    if (r.error) { ctx.err(`${target}: Temporary failure in name resolution\nCannot handle "host" cmdline arg \`${target}' on position 1 (argc 1)`); return 2; }
    ip = r.ip;
  }
  const res = send(state, ctx.vm.id, ip);
  learnArp(ctx, res);
  if (res.status === 'noroute') { ctx.err(kind === 'tracepath' ? 'connect: Network is unreachable' : `connect: Network is unreachable`); explainNet(ctx, `${kind} ${target}`, res); return 1; }
  if (kind === 'traceroute') ctx.line(`traceroute to ${target} (${ip}), 30 hops max, 60 byte packets`);
  let acc = 0;
  const hops = res.hops.slice();
  let n = 0;
  for (const h of hops) {
    n++;
    acc += h.ip.startsWith('10.0.') ? 0.35 : h.ip.startsWith('192.168.') ? 1.6 : 2.4;
    const name = rdns(h.ip, ctx);
    const t = [0, 1, 2].map(() => fmtMs(jitter(acc, Math.random())));
    if (kind === 'tracepath') ctx.line(` ${String(n).padStart(2)}:  ${name.padEnd(40)}${t[0]}ms`);
    else ctx.line(`${String(n).padStart(2)}  ${name} (${h.ip})  ${t[0]} ms  ${t[1]} ms  ${t[2]} ms`);
    if (!(await ctx.sleep(260))) return 130;
  }
  if (res.status === 'ok') {
    n++;
    const t = [0, 1, 2].map(() => fmtMs(jitter(Math.max(res.rtt, acc + 0.4), Math.random())));
    const name = rdns(ip, ctx);
    if (kind === 'tracepath') { ctx.line(` ${String(n).padStart(2)}:  ${name.padEnd(40)}${t[0]}ms reached\n     Resume: pmtu 1500 hops ${n} back ${n}`); }
    else ctx.line(`${String(n).padStart(2)}  ${name} (${ip})  ${t[0]} ms  ${t[1]} ms  ${t[2]} ms`);
  } else if (res.status === 'host_unreach' || res.status === 'net_unreach') {
    n++;
    if (kind === 'tracepath') ctx.line(` ${String(n).padStart(2)}:  ${res.errFrom || res.srcIp}  ${res.status === 'net_unreach' ? '!N' : '!H'}`);
    else ctx.line(`${String(n).padStart(2)}  ${res.errFrom || res.srcIp} (${res.errFrom || res.srcIp})  3006.1 ms !${res.status === 'net_unreach' ? 'N' : 'H'}  3006.0 ms !H  3005.9 ms !H`);
  } else {
    for (let k = n + 1; k <= 30; k++) {
      ctx.line(kind === 'tracepath' ? ` ${String(k).padStart(2)}:  no reply` : `${String(k).padStart(2)}  * * *`);
      if (!(await ctx.sleep(150))) return 130;
    }
    if (kind === 'tracepath') ctx.line('     Too many hops: pmtu 1500\n     Resume: pmtu 1500');
  }
  explainNet(ctx, `${kind} ${target}`, res);
  ctx.event({ type: 'trace', dst: ip, ok: res.status === 'ok', hops: res.hops.length });
  return 0;
}
def('traceroute', (ctx, a) => traceCore(ctx, a, 'traceroute'));
