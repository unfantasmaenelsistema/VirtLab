async function dhclientCore(ctx, ifnames, { release = false, verbose = false, viaIfup = false } = {}) {
  const rt = ctx.rt;
  const c = ctx.content;
  if (verbose || viaIfup) ctx.line('Internet Systems Consortium DHCP Client 4.4.3-P1\nCopyright 2004-2022 Internet Systems Consortium.\nAll rights reserved.\nFor info, please visit https://www.isc.org/software/dhcp/\n');
  let ok = true;
  for (const name of ifnames) {
    const i = ifaceOf(ctx, name);
    if (!i) { ctx.err(`Cannot find device "${name}"`); ok = false; continue; }
    const mac = macColon(ctx.vm.nics[i.slot].mac);
    if (verbose || viaIfup) ctx.line(`Listening on LPF/${i.name}/${mac}\nSending on   LPF/${i.name}/${mac}\nSending on   Socket/fallback`);
    if (release) {
      if (i.lease && (verbose || viaIfup)) ctx.line(`DHCPRELEASE of ${i.lease.ip} on ${i.name} to ${i.lease.server} port 67`);
      i.addrs = i.addrs.filter((x) => !x.dyn);
      rt.routes = rt.routes.filter((r) => !(r.dev === i.name && r.proto === 'dhcp'));
      i.lease = null; i.dns = (i.cfg?.dns || []).slice();
      continue;
    }
    i.admin = 'up';
    const link = linkUpOf(ctx, i);
    const server = link ? dhcpServerFor(state, ctx.vm, i.slot) : null;
    const show = (t) => { if (verbose || viaIfup) ctx.line(t); };
    show(`DHCPDISCOVER on ${i.name} to 255.255.255.255 port 67 interval 3 (xid=0x${(hashStr(mac) >>> 0).toString(16).slice(0, 8)})`);
    if (!(await ctx.sleep(700))) return 130;
    if (!server) {
      for (const iv of [5, 9, 13]) { show(`DHCPDISCOVER on ${i.name} to 255.255.255.255 port 67 interval ${iv} (xid=0x${(hashStr(mac) >>> 0).toString(16).slice(0, 8)})`); if (!(await ctx.sleep(700))) return 130; }
      show('No DHCPOFFERS received.');
      show('No working leases in persistent database - sleeping.');
      ctx.didactic({ title: `DHCP en ${i.name}`, status: 'dhcp-fail', explain: [link ? `Nadie responde al DHCPDISCOVER en ${segLabel(state, linkOf(state, ctx.vm, ctx.vm.nics[i.slot]).seg)}: ${ctx.vm.nics[i.slot].attach === 'intnet' ? 'en una red interna VirtualBox no ofrece DHCP; configura una IP estática (o monta un servidor DHCP).' : 'el servidor DHCP de esa red está deshabilitado.'}` : 'La interfaz no tiene enlace (cable desconectado o adaptador «No conectado»): el DHCPDISCOVER no sale de la máquina.'] });
      ctx.event({ type: 'dhcp', dev: i.name, ok: false });
      ok = false;
      continue;
    }
    const lease = dhcpLease(state, ctx.vm, i.slot);
    if (!lease) { show('No DHCPOFFERS received. (ámbito agotado)'); ok = false; continue; }
    show(`DHCPOFFER of ${lease.ip} from ${lease.server}`);
    if (!(await ctx.sleep(400))) return 130;
    show(`DHCPREQUEST for ${lease.ip} on ${i.name} to 255.255.255.255 port 67 (xid=0x${(hashStr(mac) >>> 0).toString(16).slice(0, 8)})`);
    if (!(await ctx.sleep(400))) return 130;
    show(`DHCPACK of ${lease.ip} from ${lease.server} (xid=0x${(hashStr(mac) >>> 0).toString(16).slice(0, 8)})`);
    i.addrs = i.addrs.filter((x) => !x.dyn);
    i.addrs.push({ ip: lease.ip, prefix: lease.prefix, dyn: true });
    i.lease = { server: lease.server, ip: lease.ip, prefix: lease.prefix, gw: lease.gw, dns: lease.dns, at: Date.now(), time: lease.lease, label: lease.label };
    rt.routes = rt.routes.filter((r) => !(r.dev === i.name && r.proto === 'dhcp'));
    if (lease.gw && !rt.routes.some((r) => r.dst === '0.0.0.0' && r.prefix === 0)) rt.routes.push({ dst: '0.0.0.0', prefix: 0, via: lease.gw, dev: i.name, proto: 'dhcp', metric: 100 + i.slot });
    if (lease.dns.length) i.dns = [...lease.dns];
    show(`bound to ${lease.ip} -- renewal in ${Math.round(lease.lease / 2)} seconds.`);
    ctx.didactic({ title: `DHCP (DORA) en ${i.name}`, status: 'ok', explain: [`D: la VM difunde DHCPDISCOVER (origen 0.0.0.0, destino 255.255.255.255) en ${segLabel(state, linkOf(state, ctx.vm, ctx.vm.nics[i.slot]).seg)}.`, `O: el ${lease.label} (${lease.server}) ofrece ${lease.ip}/${lease.prefix}.`, `R: la VM solicita formalmente esa dirección (DHCPREQUEST).`, `A: el servidor confirma (DHCPACK): IP ${lease.ip}, ${lease.gw ? `puerta de enlace ${lease.gw}` : 'sin puerta de enlace'}, ${lease.dns.length ? `DNS ${lease.dns.join(', ')}` : 'sin DNS'}, concesión de ${lease.lease} s.`] });
    ctx.event({ type: 'dhcp', dev: i.name, ok: true, ip: lease.ip });
  }
  ctx.commit();
  return ok ? 0 : 2;
}
